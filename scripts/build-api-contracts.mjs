// Builds what is generated from the LetAgents API contract (shared/api):
// 1. a `.d.mts` declaration beside each `shared/api/*.mjs`, so the server,
//    the desktop and the web app import contract types;
// 2. the compatibility snapshot, one JSON file per area in
//    `shared/api/__snapshots__/`, with every method's input and output JSON Schema.
//
//   node scripts/build-api-contracts.mjs           write both
//   node scripts/build-api-contracts.mjs --check   fail when either is stale or a change breaks the contract
//
// The snapshot is refused when the change removes a method or a field, or
// narrows a type, because `api: 1` only grows. `--allow-breaking` overrides
// that locally, for a change the owner agreed to; the check against the base
// branch's snapshot (API_CONTRACT_BASE_REF) still fails until the owner
// merges it on purpose.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CONTRACT_DIR = path.join(ROOT, "shared", "api");
export const SNAPSHOT_DIR = path.join(CONTRACT_DIR, "__snapshots__");
const REFRESH_COMMAND = "node scripts/build-api-contracts.mjs";
/** The branch API PRs merge into; CI sets API_CONTRACT_BASE_REF to the pull request's base. */
export const DEFAULT_BASE_REF = "origin/feat/letagents-api";

const COMPILER_OPTIONS = {
  allowJs: true,
  checkJs: true,
  declaration: true,
  emitDeclarationOnly: true,
  strict: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  newLine: ts.NewLineKind.LineFeed,
  types: [],
  rootDir: CONTRACT_DIR,
  // Never written: the host below keeps the output in memory.
  outDir: path.join(CONTRACT_DIR, ".declarations"),
};

function contractSources() {
  return readdirSync(CONTRACT_DIR)
    .filter((name) => name.endsWith(".mjs"))
    .sort()
    .map((name) => path.join(CONTRACT_DIR, name));
}

/**
 * Type-checks the contract modules (checkJs) and returns the declarations
 * tsc emits for them, keyed by file name (`core.d.mts`).
 * @returns {Map<string, string>}
 */
export function emitContractDeclarations() {
  const host = ts.createCompilerHost(COMPILER_OPTIONS);
  const output = new Map();
  host.writeFile = (fileName, text) => {
    const name = path.relative(COMPILER_OPTIONS.outDir, fileName);
    const source = name.replace(/\.d\.mts$/, ".mjs");
    output.set(name, `// Generated by ${REFRESH_COMMAND} from ${source}. Do not edit.\n${text}`);
  };
  const program = ts.createProgram(contractSources(), COMPILER_OPTIONS, host);
  const diagnostics = [...ts.getPreEmitDiagnostics(program)];
  const emitted = program.emit();
  diagnostics.push(...emitted.diagnostics);
  if (diagnostics.length > 0) {
    throw new Error(`The API contract does not type-check:\n${ts.formatDiagnostics(diagnostics, {
      getCanonicalFileName: (name) => name,
      getCurrentDirectory: () => ROOT,
      getNewLine: () => "\n",
    })}`);
  }
  return output;
}

/** @returns {Map<string, string>} the checked-in declarations, by file name */
function readCheckedInDeclarations() {
  return new Map(readdirSync(CONTRACT_DIR)
    .filter((name) => name.endsWith(".d.mts"))
    .map((name) => [name, readFileSync(path.join(CONTRACT_DIR, name), "utf8")]));
}

/** @returns {string[]} declaration files that are missing, stale or left over */
export function staleDeclarations(expected = emitContractDeclarations()) {
  const actual = readCheckedInDeclarations();
  const stale = [];
  for (const [name, text] of expected) if (actual.get(name) !== text) stale.push(name);
  for (const name of actual.keys()) if (!expected.has(name)) stale.push(name);
  return stale.sort();
}

/**
 * The snapshot of the contract as it is now: per area, per method name.
 * @returns {Promise<Record<string, Record<string, unknown>>>}
 */
export async function buildContractSnapshot() {
  const contract = await import(pathToFileURL(path.join(CONTRACT_DIR, "index.mjs")).href);
  const core = await import(pathToFileURL(path.join(CONTRACT_DIR, "core.mjs")).href);
  /** @type {Record<string, Record<string, unknown>>} */
  const areas = Object.fromEntries(core.API_AREAS.map((area) => [area, {}]));
  const methods = [...contract.API_METHODS].sort((a, b) => a.name.localeCompare(b.name));
  for (const method of methods) {
    const { input, output } = core.toJsonSchema(method);
    areas[method.area][method.name] = {
      kind: method.kind,
      capability: method.capability,
      httpMethod: method.httpMethod,
      path: method.path,
      response: method.response,
      rateClass: method.rateClass,
      errors: [...method.errors].sort(),
      input: withoutSchemaUri(input),
      output: withoutSchemaUri(output),
    };
  }
  return areas;
}

function withoutSchemaUri(schema) {
  const { $schema: _uri, ...rest } = schema;
  return rest;
}

/** @returns {Record<string, Record<string, unknown>>} the checked-in snapshot, per area */
export function readSnapshot() {
  let names = [];
  try {
    names = readdirSync(SNAPSHOT_DIR).filter((name) => name.endsWith(".json"));
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  return Object.fromEntries(names.sort().map((name) => [
    name.replace(/\.json$/, ""),
    JSON.parse(readFileSync(path.join(SNAPSHOT_DIR, name), "utf8")),
  ]));
}

/**
 * The snapshot as committed on the base branch, so a snapshot refreshed with
 * --allow-breaking on a feature branch still fails the check. An area file
 * missing on the base is an area with no methods yet.
 * @param {string} [ref]
 * @returns {{ ref: string, snapshot: Record<string, Record<string, unknown>> } | { ref: string, missing: string }}
 */
export function readBaseSnapshot(ref = process.env.API_CONTRACT_BASE_REF || DEFAULT_BASE_REF) {
  const git = (...args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  try {
    git("rev-parse", "--verify", "--quiet", `${ref}^{commit}`);
  } catch {
    return { ref, missing: `the base ref ${ref} is not in this clone (fetch it to compare)` };
  }
  let listing = "";
  try {
    listing = git("ls-tree", "--name-only", `${ref}:shared/api/__snapshots__`).trim();
  } catch {
    // No snapshot directory on the base yet: nothing to break.
  }
  const snapshot = {};
  for (const name of listing ? listing.split("\n") : []) {
    if (!name.endsWith(".json")) continue;
    snapshot[name.replace(/\.json$/, "")] = JSON.parse(git("show", `${ref}:shared/api/__snapshots__/${name}`));
  }
  return { ref, snapshot };
}

const snapshotText = (methods) => `${JSON.stringify(methods, null, 2)}\n`;

/** @returns {string[]} areas whose snapshot file differs from the contract */
export function staleSnapshotAreas(current, checkedIn = readSnapshot()) {
  const areas = new Set([...Object.keys(current), ...Object.keys(checkedIn)]);
  return [...areas].filter((area) => snapshotText(current[area] ?? {}) !== snapshotText(checkedIn[area] ?? {})).sort();
}

const flatten = (snapshot) => Object.assign({}, ...Object.values(snapshot));

// ── Compatibility rules ──────────────────────────────────────────────────
// A client written for an older snapshot must keep working:
// - inputs: everything the old schema accepted is still accepted (no removed
//   field, no new required field, no narrower type, enum, limit or pattern);
// - outputs: every field the old schema promised is still there, with no new
//   type, and does not become optional or nullable.
// New methods, new optional input fields, new output fields and new output
// enum values are additions and pass: clients must accept enum values they
// do not know yet.

/**
 * @param {Record<string, Record<string, unknown>>} before snapshot per area
 * @param {Record<string, Record<string, unknown>>} after snapshot per area
 * @returns {string[]} one sentence per breaking change
 */
export function findBreakingChanges(before, after) {
  const oldMethods = flatten(before);
  const newMethods = flatten(after);
  const problems = [];
  for (const [name, old] of Object.entries(oldMethods)) {
    const now = newMethods[name];
    if (!now) {
      problems.push(`${name}: the method was removed.`);
      continue;
    }
    // A rate class change is breaking too: a client paced for the old limit
    // can start to fail. Snapshots made before `response` existed mean "json".
    for (const key of ["kind", "capability", "httpMethod", "path", "rateClass", "response"]) {
      const [was, is] = key === "response" ? [old[key] ?? "json", now[key] ?? "json"] : [old[key], now[key]];
      if (was !== is) problems.push(`${name}: ${key} changed from ${JSON.stringify(was)} to ${JSON.stringify(is)}.`);
    }
    compareSchema(old.input, now.input, "input", `${name} input`, problems, { rootA: old.input, rootB: now.input, open: new Set() });
    compareSchema(old.output, now.output, "output", `${name} output`, problems, { rootA: old.output, rootB: now.output, open: new Set() });
  }
  return problems;
}

const LOWER_BOUNDS = ["minLength", "minimum", "exclusiveMinimum", "minItems", "minProperties"];
const UPPER_BOUNDS = ["maxLength", "maximum", "exclusiveMaximum", "maxItems", "maxProperties"];

function alternatives(schema) {
  return schema.anyOf ?? schema.oneOf ?? [schema];
}

function typesOf(schema) {
  if (schema.type === undefined) return null;
  return Array.isArray(schema.type) ? schema.type : [schema.type];
}

const isNullSchema = (schema) => (typesOf(schema)?.length === 1 && schema.type === "null") || schema.const === null;
const allowsNull = (schema) => alternatives(schema).some((alt) => typesOf(alt)?.includes("null") || alt.const === null);
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/** `#`, `#/$defs/Task`: a JSON pointer into the schema's own root. */
function resolveRef(root, ref) {
  if (ref === "#") return root;
  if (!ref.startsWith("#/")) return undefined;
  let node = root;
  for (const part of ref.slice(2).split("/")) node = node?.[part.replace(/~1/g, "/").replace(/~0/g, "~")];
  return isSchema(node) ? node : undefined;
}

function compareSchema(a, b, mode, at, problems, ctx) {
  if (a.$ref !== undefined || b.$ref !== undefined) {
    // Follow references into $defs; a pair already being compared further up
    // is a recursive schema, compared once.
    const pair = `${mode}|${a.$ref ?? "-"}|${b.$ref ?? "-"}`;
    if (ctx.open.has(pair)) return;
    const resolvedA = a.$ref === undefined ? a : resolveRef(ctx.rootA, a.$ref);
    const resolvedB = b.$ref === undefined ? b : resolveRef(ctx.rootB, b.$ref);
    if (!resolvedA || !resolvedB) {
      problems.push(`${at}: the reference ${(resolvedA ? b : a).$ref} does not resolve.`);
      return;
    }
    ctx.open.add(pair);
    compareSchema(withoutRef(resolvedA, a), withoutRef(resolvedB, b), mode, at, problems, ctx);
    ctx.open.delete(pair);
    return;
  }
  if (same(a, b) && same(ctx.rootA.$defs, ctx.rootB.$defs)) return;
  const altsA = alternatives(a);
  const altsB = alternatives(b);
  if (altsA.length > 1 || altsB.length > 1) {
    const fits = (from, to) => {
      const trial = [];
      compareSchema(from, to, mode, at, trial, ctx);
      return trial.length === 0;
    };
    if (mode === "input") {
      // Each shape the old input accepted is still accepted by some new one.
      for (const alt of altsA) {
        if (!altsB.some((candidate) => fits(alt, candidate))) problems.push(`${at}: ${JSON.stringify(alt)} is no longer accepted.`);
      }
      return;
    }
    // Each shape the new output returns is one the old output promised.
    for (const alt of altsB) {
      if (isNullSchema(alt)) continue;
      if (!altsA.some((candidate) => fits(candidate, alt))) problems.push(`${at}: ${JSON.stringify(alt)} is a new kind of value.`);
    }
    if (!allowsNull(a) && allowsNull(b)) problems.push(`${at}: can now be null.`);
    return;
  }

  const typesA = typesOf(a);
  const typesB = typesOf(b);
  if (typesA && typesB && mode === "input") {
    for (const type of typesA) {
      const kept = typesB.includes(type) || (type === "integer" && typesB.includes("number"));
      if (!kept) problems.push(`${at}: the type ${type} is no longer accepted.`);
    }
  } else if (typesA && typesB) {
    for (const type of typesB) {
      if (typesA.includes(type)) continue;
      problems.push(type === "null" ? `${at}: can now be null.` : `${at}: the type ${type} is now returned.`);
    }
  } else if (typesA && !typesB && mode === "output") {
    problems.push(`${at}: is no longer typed.`);
  } else if (!typesA && typesB && mode === "input") {
    problems.push(`${at}: now accepts only ${typesB.join(" or ")}.`);
  }

  if (mode === "input" && Array.isArray(b.enum)) {
    const removed = Array.isArray(a.enum) ? a.enum.filter((value) => !b.enum.some((other) => same(value, other))) : null;
    if (!removed) problems.push(`${at}: now accepts only ${JSON.stringify(b.enum)}.`);
    else if (removed.length) problems.push(`${at}: the values ${JSON.stringify(removed)} are no longer accepted.`);
  }
  if ("const" in b && (!("const" in a) ? mode === "input" : !same(a.const, b.const))) {
    problems.push(`${at}: is now fixed to ${JSON.stringify(b.const)}.`);
  }

  if (mode === "input") {
    for (const key of LOWER_BOUNDS) {
      if (b[key] !== undefined && (a[key] === undefined || b[key] > a[key])) problems.push(`${at}: ${key} was raised to ${b[key]}.`);
    }
    for (const key of UPPER_BOUNDS) {
      if (b[key] !== undefined && (a[key] === undefined || b[key] < a[key])) problems.push(`${at}: ${key} was lowered to ${b[key]}.`);
    }
    for (const key of ["pattern", "format"]) {
      if (b[key] !== undefined && b[key] !== a[key]) problems.push(`${at}: the ${key} changed to ${JSON.stringify(b[key])}.`);
    }
  }

  if (a.properties || b.properties) {
    const propsA = a.properties ?? {};
    const propsB = b.properties ?? {};
    const requiredA = new Set(a.required ?? []);
    const requiredB = new Set(b.required ?? []);
    for (const [key, schema] of Object.entries(propsA)) {
      if (!(key in propsB)) {
        problems.push(`${at}.${key}: the field was removed.`);
        continue;
      }
      compareSchema(schema, propsB[key], mode, `${at}.${key}`, problems, ctx);
      if (mode === "input" && !requiredA.has(key) && requiredB.has(key)) problems.push(`${at}.${key}: is now required.`);
      if (mode === "output" && requiredA.has(key) && !requiredB.has(key)) problems.push(`${at}.${key}: is no longer always present.`);
    }
    if (mode === "input") {
      for (const key of requiredB) if (!(key in propsA)) problems.push(`${at}.${key}: a new required field.`);
    }
  }
  if (mode === "input" && a.additionalProperties !== false && b.additionalProperties === false) {
    problems.push(`${at}: unknown fields are now refused.`);
  }
  if (isSchema(a.additionalProperties) && isSchema(b.additionalProperties)) {
    compareSchema(a.additionalProperties, b.additionalProperties, mode, `${at}{*}`, problems, ctx);
  }
  if (isSchema(a.items) && isSchema(b.items)) compareSchema(a.items, b.items, mode, `${at}[]`, problems, ctx);
}

const isSchema = (value) => value !== null && typeof value === "object" && !Array.isArray(value);

/** A `$ref` node's own keywords (a description, a default) laid over its target. */
function withoutRef(target, node) {
  const { $ref: _ref, ...rest } = node;
  return { ...target, ...rest };
}

// ── CLI ──────────────────────────────────────────────────────────────────

function writeDeclarations(declarations) {
  for (const name of readdirSync(CONTRACT_DIR)) {
    if (name.endsWith(".d.mts") && !declarations.has(name)) rmSync(path.join(CONTRACT_DIR, name));
  }
  for (const [name, text] of declarations) writeFileSync(path.join(CONTRACT_DIR, name), text);
}

function writeSnapshot(snapshot) {
  mkdirSync(SNAPSHOT_DIR, { recursive: true });
  for (const name of readdirSync(SNAPSHOT_DIR)) {
    if (name.endsWith(".json") && !(name.replace(/\.json$/, "") in snapshot)) rmSync(path.join(SNAPSHOT_DIR, name));
  }
  for (const [area, methods] of Object.entries(snapshot)) {
    writeFileSync(path.join(SNAPSHOT_DIR, `${area}.json`), snapshotText(methods));
  }
}

async function main(argv) {
  const check = argv.includes("--check");
  const allowBreaking = argv.includes("--allow-breaking");
  const declarations = emitContractDeclarations();
  const snapshot = await buildContractSnapshot();
  const breaking = findBreakingChanges(readSnapshot(), snapshot);

  if (check) {
    const base = readBaseSnapshot();
    if ("missing" in base) console.warn(`Not compared with the base branch: ${base.missing}.`);
    const problems = [
      ...staleDeclarations(declarations).map((name) => `shared/api/${name} is stale.`),
      ...staleSnapshotAreas(snapshot).map((area) => `shared/api/__snapshots__/${area}.json is stale.`),
      ...breaking,
      ...("snapshot" in base ? findBreakingChanges(base.snapshot, snapshot).map((problem) => `against ${base.ref}: ${problem}`) : []),
    ];
    if (problems.length) throw new Error(`The API contract check failed:\n- ${problems.join("\n- ")}\nRun ${REFRESH_COMMAND} for stale files.`);
    console.log("The API contract declarations and snapshot are current.");
    return;
  }

  writeDeclarations(declarations);
  if (breaking.length && !allowBreaking) {
    throw new Error(`Declarations written; the snapshot was not, because the change breaks api: 1:\n- ${breaking.join("\n- ")}\n`
      + "Make the change additive (a new field or method), or pass --allow-breaking if the owner agreed.");
  }
  writeSnapshot(snapshot);
  console.log(`Wrote ${declarations.size} declaration files and the snapshot of ${Object.values(snapshot).reduce((n, area) => n + Object.keys(area).length, 0)} methods.`);
}

const isMain = process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
